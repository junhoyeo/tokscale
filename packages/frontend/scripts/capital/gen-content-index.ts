/**
 * Regenerate src/lib/capital/ledger/contentIndex.generated.ts from the JSON files on disk.
 *
 * JSON content is bundled through static imports (no fs reads at runtime), so every
 * event, org and statement file must be imported. Run this after adding or removing a file:
 *
 *   bun scripts/capital/gen-content-index.ts          # write the index
 *   bun scripts/capital/gen-content-index.ts --check  # exit 1 if the index is stale
 *
 * The output is sorted and deterministic, so concurrent runs agree.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..", "..");
const CONTENT = join(ROOT, "src", "content", "capital");
const OUT = join(ROOT, "src", "lib", "capital", "ledger", "contentIndex.generated.ts");

const jsonFiles = (dir: string, pattern: RegExp) =>
  readdirSync(dir)
    .filter((name) => name.endsWith(".json") && pattern.test(name))
    .sort();

const groups: Array<{ exportName: string; dir: string; importDir: string; files: string[] }> = [
  { exportName: "ORG_FILES", dir: CONTENT, importDir: "@/content/capital", files: jsonFiles(CONTENT, /^orgs(?:-[a-z0-9-]+)?\.json$/) },
  { exportName: "EVENT_FILES", dir: join(CONTENT, "events"), importDir: "@/content/capital/events", files: jsonFiles(join(CONTENT, "events"), /./) },
  {
    exportName: "STATEMENT_FILES",
    dir: join(CONTENT, "metrics"),
    importDir: "@/content/capital/metrics",
    files: jsonFiles(join(CONTENT, "metrics"), /^statements(?:-[a-z0-9-]+)?\.json$/),
  },
];

const lines: string[] = [
  "// Generated by scripts/capital/gen-content-index.ts. Do not edit by hand.",
  "// Run `bun scripts/capital/gen-content-index.ts` after adding or removing a content file.",
];
const exportsOut: string[] = [];
let n = 0;
for (const group of groups) {
  const names: string[] = [];
  for (const file of group.files) {
    const name = `${group.exportName.toLowerCase().replace(/_files$/, "")}${n++}`;
    lines.push(`import ${name} from "${group.importDir}/${file}";`);
    names.push(name);
  }
  exportsOut.push(`export const ${group.exportName}: ReadonlyArray<{ file: string; data: unknown }> = [`);
  group.files.forEach((file, i) => exportsOut.push(`  { file: "${file}", data: ${names[i]} },`));
  exportsOut.push("];");
}
const source = `${lines.join("\n")}\n\n${exportsOut.join("\n")}\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // missing counts as stale
  }
  if (current !== source) {
    console.error("contentIndex.generated.ts is stale. Run: bun scripts/capital/gen-content-index.ts");
    process.exit(1);
  }
  console.log("contentIndex.generated.ts is up to date.");
} else {
  writeFileSync(OUT, source);
  console.log(`Wrote ${OUT} (${groups.map((g) => `${g.files.length} ${g.exportName}`).join(", ")}).`);
}
